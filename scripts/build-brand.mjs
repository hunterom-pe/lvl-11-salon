/**
 * Generates every LVL 11 brand asset from the procedural brush geometry:
 *   public/brand/*.svg        logo lockups for light + dark backgrounds
 *   public/favicon.svg        simplified "11" mark
 *   public/*.png              apple-touch / PWA icons
 *   public/og-image.jpg       1200×630 social card
 *   src/brand/logo-data.ts    path data consumed by the <Logo> component
 */
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'
import { VIEW, SALON, brushPath, logoSVG, faviconPath, swashPath } from './logo-geometry.mjs'

const root = path.resolve(import.meta.dirname, '..')
const pub = (...p) => path.join(root, 'public', ...p)
await mkdir(pub('brand'), { recursive: true })
await mkdir(path.join(root, 'src/brand'), { recursive: true })

const CHARCOAL = '#292C2A'
const IVORY = '#F5F1EA'
const SKY = '#A4C1CC'
const brush = brushPath()

// ——— Logo lockups ———
await writeFile(pub('brand/lvl11-logo-charcoal.svg'), logoSVG({ color: CHARCOAL }))
await writeFile(pub('brand/lvl11-logo-ivory.svg'), logoSVG({ color: IVORY }))
const markOnly = (c) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW.w} 360" role="img" aria-label="LVL 11"><title>LVL 11</title><path fill="${c}" d="${brush}"/></svg>`
await writeFile(pub('brand/lvl11-wordmark-charcoal.svg'), markOnly(CHARCOAL))
await writeFile(pub('brand/lvl11-wordmark-ivory.svg'), markOnly(IVORY))

// ——— Favicon ———
const fav = faviconPath()
const favicon = (size = 64) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${size}" height="${size}"><rect width="64" height="64" rx="12" fill="${CHARCOAL}"/><path fill="${IVORY}" d="${fav}"/></svg>`
await writeFile(pub('favicon.svg'), favicon())
for (const [name, size] of [['apple-touch-icon.png', 180], ['icon-192.png', 192], ['icon-512.png', 512], ['favicon-32.png', 32]]) {
  // apple icons get a full-bleed square (iOS rounds corners itself)
  const svg = name.startsWith('apple')
    ? favicon(size).replace('rx="12"', 'rx="0"')
    : favicon(size)
  await sharp(Buffer.from(svg), { density: 72 * (size / 64) * 2 }).resize(size, size).png().toFile(pub(name))
}

// ——— Social card ———
try {
  const hero = await readFile(path.join(root, '.image-cache/hero.jpg'))
  const photo = await sharp(hero).resize(1200, 630, { fit: 'cover', position: sharp.gravity.north }).modulate({ brightness: 0.92 }).toBuffer()
  const overlay = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0.35" stop-color="${CHARCOAL}" stop-opacity="0"/><stop offset="1" stop-color="${CHARCOAL}" stop-opacity="0.78"/></linearGradient></defs>
    <rect width="1200" height="630" fill="url(#g)"/>
    <svg x="56" y="300" width="620" height="${(620 * VIEW.h) / VIEW.w}" viewBox="0 0 ${VIEW.w} ${VIEW.h}">
      <path fill="${IVORY}" d="${brush}"/>
      <g fill="none" stroke="${IVORY}" stroke-width="${SALON.stroke}" stroke-linecap="square" stroke-miterlimit="1.5">${SALON.svg}</g>
    </svg>
    <text x="1144" y="574" text-anchor="end" font-family="Helvetica, Arial, sans-serif" font-size="22" letter-spacing="5" fill="${IVORY}">PHOENIX · ARIZONA</text>
  </svg>`
  await sharp(photo).composite([{ input: Buffer.from(overlay) }]).jpeg({ quality: 82, mozjpeg: true }).toFile(pub('og-image.jpg'))
} catch (e) {
  console.warn('og-image skipped (run `npm run images` first):', e.message)
}

// ——— Data module for React ———
await writeFile(
  path.join(root, 'src/brand/logo-data.ts'),
  `// AUTO-GENERATED by scripts/build-brand.mjs. Do not edit by hand.
export const LOGO_VIEW = { w: ${VIEW.w}, h: ${VIEW.h} } as const
export const BRUSH_D = ${JSON.stringify(brush)}
export const SALON_GLYPHS: ReadonlyArray<{ x: number; d: string }> = ${JSON.stringify(SALON.glyphs)}
export const SALON_STROKE = ${SALON.stroke}
export const SALON_BOX = { x: ${SALON.start}, y: 394, w: ${SALON.end - SALON.start}, h: ${SALON.height} } as const
export const SWASH_D = ${JSON.stringify(swashPath())}
export const SKY = '${SKY}'
`,
)
console.log('brand assets written')
